// Command gen writes compiler/text's tables_gen.go from the Unicode
// Character Database (ADR 0067): grapheme cluster break properties,
// Extended_Pictographic, the unconditional full case mappings, and full case
// folding. The version is pinned to the one Go's unicode package carries,
// so whitespace and simple case mapping, which come from Go, agree with the
// tables generated here.
//
// Run from compiler/text: go generate. It downloads from unicode.org, or
// reads the files from -ucd if given.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

var ucd = flag.String("ucd", "", "directory holding the data files, instead of downloading them")

func main() {
	flag.Parse()
	breaks := ranges(read("auxiliary/GraphemeBreakProperty.txt"), func(string) bool { return true })
	pict := ranges(read("emoji/emoji-data.txt"), func(p string) bool { return p == "Extended_Pictographic" })
	upper, lower := specialCasing(read("SpecialCasing.txt"))
	fold := caseFolding(read("CaseFolding.txt"))

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/gen from Unicode %s. DO NOT EDIT.\n\npackage text\n\n", unicode.Version)
	fmt.Fprintf(&b, "// UnicodeVersion is the version every table here and Go's unicode package\n// come from (ADR 0067 §1).\nconst UnicodeVersion = %q\n\n", unicode.Version)
	b.WriteString("var breakRanges = []breakRange{\n")
	for _, r := range breaks {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, prop%s},\n", r.lo, r.hi, strings.ReplaceAll(r.prop, "_", ""))
	}
	b.WriteString("}\n\nvar pictographicRanges = []breakRange{\n")
	for _, r := range pict {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, 0},\n", r.lo, r.hi)
	}
	b.WriteString("}\n\n")
	writeMap(&b, "specialUpper", upper)
	writeMap(&b, "specialLower", lower)
	writeMap(&b, "foldings", fold)
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func read(name string) []byte {
	if *ucd != "" {
		data, err := os.ReadFile(filepath.Join(*ucd, filepath.Base(name)))
		if err != nil {
			log.Fatal(err)
		}
		return data
	}
	url := "https://www.unicode.org/Public/" + unicode.Version + "/ucd/" + name
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return data
}

type rng struct {
	lo, hi uint32
	prop   string
}

// ranges reads a `code(..code)? ; Property # comment` file, keeping the
// properties keep accepts, sorted and with adjacent equal ranges merged.
func ranges(data []byte, keep func(string) bool) []rng {
	var out []rng
	for _, f := range lines(data) {
		if len(f) < 2 || !keep(f[1]) {
			continue
		}
		lo, hi, _ := strings.Cut(f[0], "..")
		if hi == "" {
			hi = lo
		}
		out = append(out, rng{hex(lo), hex(hi), f[1]})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].lo < out[j].lo })
	merged := out[:0]
	for _, r := range out {
		if n := len(merged); n > 0 && merged[n-1].hi+1 == r.lo && merged[n-1].prop == r.prop {
			merged[n-1].hi = r.hi
			continue
		}
		merged = append(merged, r)
	}
	return merged
}

// specialCasing keeps the entries with no condition: a condition is either
// a language (tr, lt, az) or a context (Final_Sigma), and ADR 0067 §4 maps
// without either.
func specialCasing(data []byte) (upper, lower map[rune]string) {
	upper, lower = map[rune]string{}, map[rune]string{}
	for _, f := range lines(data) {
		if len(f) < 4 || (len(f) > 4 && f[4] != "") {
			continue
		}
		r := rune(hex(f[0]))
		if s := codes(f[3]); s != string(unicode.ToUpper(r)) {
			upper[r] = s
		}
		if s := codes(f[1]); s != string(unicode.ToLower(r)) {
			lower[r] = s
		}
	}
	return upper, lower
}

// caseFolding keeps statuses C (common) and F (full); S is the simple
// alternative to F, and T is Turkic.
func caseFolding(data []byte) map[rune]string {
	fold := map[rune]string{}
	for _, f := range lines(data) {
		if len(f) >= 3 && (f[1] == "C" || f[1] == "F") {
			fold[rune(hex(f[0]))] = codes(f[2])
		}
	}
	return fold
}

// lines splits each non-comment line into its trimmed `;` fields.
func lines(data []byte) [][]string {
	var out [][]string
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		if strings.TrimSpace(line) == "" {
			continue
		}
		f := strings.Split(line, ";")
		for i := range f {
			f[i] = strings.TrimSpace(f[i])
		}
		out = append(out, f)
	}
	return out
}

func hex(s string) uint32 {
	n, err := strconv.ParseUint(s, 16, 32)
	if err != nil {
		log.Fatalf("bad code point %q", s)
	}
	return uint32(n)
}

func codes(s string) string {
	var b strings.Builder
	for _, c := range strings.Fields(s) {
		b.WriteRune(rune(hex(c)))
	}
	return b.String()
}

func writeMap(b *bytes.Buffer, name string, m map[rune]string) {
	keys := make([]rune, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	fmt.Fprintf(b, "var %s = map[rune]string{\n", name)
	for _, k := range keys {
		fmt.Fprintf(b, "\t0x%04X: %q,\n", k, m[k])
	}
	b.WriteString("}\n\n")
}
